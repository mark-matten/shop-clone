// Generate a clothing image from description using Nano Banana (non-Pro for cost savings)
export const generateClothingImage = action({
  args: {
    clerkId: v.string(),
    description: v.string(),
    brand: v.optional(v.string()),
    color: v.optional(v.string()),
    material: v.optional(v.string()),
    category: v.string(),
    size: v.optional(v.string()),
    gender: v.union(v.literal("men"), v.literal("women"), v.literal("unisex")),
    isWishlist: v.optional(v.boolean()), // true = wishlist, false/undefined = owned
  },
  handler: async (ctx, args) => {
    const apiKey = process.env.GOOGLE_GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error("GOOGLE_GEMINI_API_KEY environment variable not set");
    }

    // Build the prompt for clothing image generation
    const promptParts = [
      `Generate a professional product photo of a ${args.category} clothing item.`,
      `Item description: ${args.description}`,
    ];

    if (args.brand) {
      promptParts.push(`Brand style: ${args.brand}`);
    }
    if (args.color) {
      promptParts.push(`Color: ${args.color}`);
    }
    if (args.material) {
      promptParts.push(`Material: ${args.material}`);
    }

    promptParts.push(
      "",
      "Requirements for product photography:",
      "- Soft neutral background - can be light gray, beige, cream, or a subtle gradient",
      "- FLAT LAY style: item laid flat on a surface, photographed from directly above",
      "- Even, soft studio lighting - no harsh shadows",
      "- No human models, mannequins, or body parts - just the clothing item",
      "- Item centered in frame with some breathing room around edges",
      "- Clean, minimalist aesthetic"
    );

    const prompt = promptParts.join("\n");

    // Call Nano Banana (Gemini 2.5 Flash Image) API for image generation
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          contents: [
            {
              parts: [
                {
                  text: prompt,
                },
              ],
            },
          ],
          generationConfig: {
            responseModalities: ["TEXT", "IMAGE"],
          },
        }),
      }
    );

    if (!response.ok) {
      const errorText = await response.text();
      console.error("Gemini API error response:", errorText);
      let errorMessage = `Gemini API error: ${response.status}`;
      try {
        const errorJson = JSON.parse(errorText);
        if (errorJson.error?.message) {
          errorMessage = `Gemini: ${errorJson.error.message}`;
        }
      } catch {
        // Keep the original error message
      }
      throw new Error(errorMessage);
    }

    const result = await response.json();

    // Extract the image data from the response
    const imageData = result.candidates?.[0]?.content?.parts?.find(
      (part: { inlineData?: { mimeType: string; data: string } }) =>
        part.inlineData?.mimeType?.startsWith("image/")
    );

    if (!imageData?.inlineData?.data) {
      console.error("No image in Gemini response");
      throw new Error("No image generated by Gemini");
    }

    // Convert base64 to blob and upload to Convex storage
    const imageBytes = Uint8Array.from(atob(imageData.inlineData.data), (c) =>
      c.charCodeAt(0)
    );
    const blob = new Blob([imageBytes], {
      type: imageData.inlineData.mimeType,
    });

    // Upload to Convex storage
    const storageId = await ctx.storage.store(blob);

    // Create closet item with generated image
    const closetItemId: Id<"closet_items"> = await ctx.runMutation(
      internal.gemini.createGeneratedClosetItem,
      {
        clerkId: args.clerkId,
        name: args.description,
        brand: args.brand,
        color: args.color,
        material: args.material,
        category: args.category,
        size: args.size,
        gender: args.gender,
        generatedImageStorageId: storageId,
        userDescription: args.description,
        isWishlist: args.isWishlist,
      }
    );

    // Get the image URL
    const imageUrl = await ctx.storage.getUrl(storageId);

    return {
      closetItemId,
      storageId,
      imageUrl,
    };
  },
});

// Internal mutation to create closet item with generated image
export const createGeneratedClosetItem = internalMutation({
  args: {
    clerkId: v.string(),
    name: v.string(),
    brand: v.optional(v.string()),
    color: v.optional(v.string()),
    material: v.optional(v.string()),
    category: v.string(),
    size: v.optional(v.string()),
    gender: v.union(v.literal("men"), v.literal("women"), v.literal("unisex")),
    generatedImageStorageId: v.id("_storage"),
    userDescription: v.string(),
    isWishlist: v.optional(v.boolean()),
  },
  handler: async (ctx, args) => {
    // Get or create user
    const user = await ctx.db
      .query("users")
      .withIndex("by_clerkId", (q) => q.eq("clerkId", args.clerkId))
      .first();

    if (!user) {
      throw new Error("User not found");
    }

    // Get next sort order
    const existingItems = await ctx.db
      .query("closet_items")
      .withIndex("by_userId", (q) => q.eq("userId", user._id))
      .collect();

    const maxSortOrder = Math.max(
      0,
      ...existingItems.map((item) => item.sortOrder ?? 0)
    );

    // Create closet item (used for both owned and wishlist generated items)
    return await ctx.db.insert("closet_items", {
      userId: user._id,
      addedAt: Date.now(),
      source: "generated",
      name: args.name,
      brand: args.brand,
      color: args.color,
      material: args.material,
      category: args.category,
      size: args.size,
      gender: args.gender,
      generatedImageStorageId: args.generatedImageStorageId,
      userDescription: args.userDescription,
      sortOrder: maxSortOrder + 1,
      isWishlist: args.isWishlist || false,
    });
  },
});

// Generate a virtual try-on image
export const generateTryOnImage = action({
  args: {
    clerkId: v.string(),
    productIds: v.array(v.string()), // Accept string productIds (works for both owned and wishlist)
    userPhotoStorageId: v.optional(v.id("_storage")),
    useGenericModel: v.boolean(),
    gender: v.optional(v.union(v.literal("female"), v.literal("male"))),
    // Model customization (for generic model)
    modelHeight: v.optional(v.number()), // inches
    modelWeight: v.optional(v.number()), // lbs
    modelSkinTone: v.optional(v.number()), // 0-100 scale
    otherDetails: v.optional(v.string()), // e.g., "cuffed pants, shirt tucked in"
  },
  handler: async (ctx, args) => {
    const apiKey = process.env.GOOGLE_GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error("GOOGLE_GEMINI_API_KEY environment variable not set");
    }

    // Fetch products directly by productId
    const items = await Promise.all(
      args.productIds
        .filter((id) => !id.startsWith("url-") && !id.startsWith("gen-")) // Skip non-product items for now
        .map((id) =>
          ctx.runQuery(internal.gemini.getProductWithImage, { productId: id as Id<"products"> })
        )
    );

    const validItems = items.filter((item): item is NonNullable<typeof item> => item !== null);
    if (validItems.length === 0) {
      throw new Error("No valid items provided");
    }

    // Build prompt
    const promptParts: string[] = [];

    // Determine gender for the model (default to female if not specified)
    const modelGender = args.gender || "female";
    const genderDescription = modelGender === "male" ? "male" : "female";

    // Helper to convert height in inches to feet/inches description
    const formatHeight = (inches: number) => {
      const feet = Math.floor(inches / 12);
      const remainingInches = inches % 12;
      return `${feet}'${remainingInches}"`;
    };

    // Helper to convert skin tone (0-100) to description
    const getSkinToneDescription = (tone: number) => {
      if (tone < 20) return "fair/light";
      if (tone < 40) return "light-medium";
      if (tone < 60) return "medium";
      if (tone < 80) return "medium-dark";
      return "dark/deep";
    };

    if (args.userPhotoStorageId && !args.useGenericModel) {
      promptParts.push(
        `Generate a FULL BODY fashion photo of a real ${genderDescription} person wearing an outfit.`,
        "Use the provided reference photo to match the person's appearance, face, and body type exactly.",
        "Show the person's face clearly with a friendly, moderate smile.",
        "IMPORTANT: Use a real human model, NOT a mannequin or faceless figure.",
        ""
      );
    } else {
      // Build model description for generic model
      const modelDescParts = [`a real ${genderDescription} model`];
      if (args.modelHeight) {
        modelDescParts.push(`approximately ${formatHeight(args.modelHeight)} tall`);
      }
      if (args.modelWeight) {
        modelDescParts.push(`with a ${args.modelWeight < 130 ? "slim" : args.modelWeight < 170 ? "average" : args.modelWeight < 200 ? "athletic" : "full"} build (around ${args.modelWeight} lbs)`);
      }
      if (args.modelSkinTone !== undefined) {
        modelDescParts.push(`with ${getSkinToneDescription(args.modelSkinTone)} skin tone`);
      }

      promptParts.push(
        `Generate a FULL BODY fashion photo of ${modelDescParts.join(", ")} wearing an outfit.`,
        "The model should have a friendly, moderate smile and relaxed, natural pose.",
        "Show the ENTIRE body from head to toe, standing upright.",
        "IMPORTANT: Use a real human model, NOT a mannequin or faceless figure.",
        ""
      );
    }

    promptParts.push(
      "Outfit items (reference images provided below - MATCH EXACTLY):"
    );

    for (const item of validItems) {
      const desc = [item.name];
      if (item.brand) desc.push(`by ${item.brand}`);
      if (item.color) desc.push(`in ${item.color}`);
      if (item.material) desc.push(`made of ${item.material}`);
      promptParts.push(`- ${desc.join(" ")}`);
    }

    // Add other details if specified (e.g., "cuffed pants, shirt tucked in")
    if (args.otherDetails) {
      promptParts.push("", `Styling details: ${args.otherDetails}`);
    }

    promptParts.push(
      "",
      "CRITICAL - Clothing Accuracy Requirements:",
      "- MATCH EXACT COLOR of each item from reference images (no color substitutions)",
      "- MATCH EXACT FIT AND SILHOUETTE (slim, relaxed, oversized, cropped, etc.)",
      "- MATCH EXACT STYLE AND DESIGN (neckline, collar, buttons, pockets, seams, patterns)",
      "- MATCH EXACT TEXTURE AND MATERIAL appearance (knit, woven, leather, denim, etc.)",
      "- MATCH EXACT DETAILS (stitching, hardware, logos, embellishments)",
      "- Each clothing item must be RECOGNIZABLE as the specific item from the reference",
      "",
      "Photo Style Requirements:",
      "- FULL BODY shot showing head to toe, model standing upright",
      "- Relaxed, natural standing pose with slight weight shift",
      "- Friendly, moderate smile on face",
      "- Neutral, clean background (solid light gray or white studio backdrop)",
      "- Even, consistent studio lighting from multiple angles",
      "- No harsh shadows or dramatic lighting",
      "- High quality, professional fashion photography"
    );

    const textPrompt = promptParts.join("\n");

    // Build the request with images
    const contentParts: Array<
      | { text: string }
      | { inlineData: { mimeType: string; data: string } }
    > = [];

    // Add text prompt
    contentParts.push({ text: textPrompt });

    // Add user photo if provided
    if (args.userPhotoStorageId && !args.useGenericModel) {
      const photoBlob = await ctx.storage.get(args.userPhotoStorageId);
      if (photoBlob) {
        const arrayBuffer = await photoBlob.arrayBuffer();
        const base64 = arrayBufferToBase64(arrayBuffer);
        contentParts.push({
          inlineData: {
            mimeType: photoBlob.type || "image/jpeg",
            data: base64,
          },
        });
        contentParts.push({
          text: "(Above is the reference photo - match this person's appearance, face, and body type exactly.)",
        });
      }
    }

    // Add clothing item images
    for (const item of validItems) {
      const itemWithImage = item as typeof item & { imageStorageId?: Id<"_storage">; imageUrl?: string | null };
      if (itemWithImage.imageStorageId) {
        const itemBlob = await ctx.storage.get(itemWithImage.imageStorageId);
        if (itemBlob) {
          const arrayBuffer = await itemBlob.arrayBuffer();
          const base64 = arrayBufferToBase64(arrayBuffer);
          contentParts.push({
            inlineData: {
              mimeType: itemBlob.type || "image/jpeg",
              data: base64,
            },
          });
          const itemDesc = [item.name];
          if (item.color) itemDesc.push(`in ${item.color}`);
          if (item.material) itemDesc.push(`made of ${item.material}`);
          contentParts.push({
            text: `(REFERENCE IMAGE for ${item.category || "clothing item"}: ${itemDesc.join(" ")} - MATCH THIS EXACT ITEM: color, fit, texture, design, and all details)`,
          });
        }
      } else if (itemWithImage.imageUrl) {
        // If we have a URL but no storage ID, fetch the image
        try {
          const response = await fetch(itemWithImage.imageUrl);
          if (response.ok) {
            const arrayBuffer = await response.arrayBuffer();
            const base64 = arrayBufferToBase64(arrayBuffer);
            const mimeType =
              response.headers.get("content-type") || "image/jpeg";
            contentParts.push({
              inlineData: {
                mimeType,
                data: base64,
              },
            });
            const itemDesc = [item.name];
            if (item.color) itemDesc.push(`in ${item.color}`);
            if (item.material) itemDesc.push(`made of ${item.material}`);
            contentParts.push({
              text: `(REFERENCE IMAGE for ${item.category || "clothing item"}: ${itemDesc.join(" ")} - MATCH THIS EXACT ITEM: color, fit, texture, design, and all details)`,
            });
          }
        } catch (e) {
          console.warn(`Failed to fetch image for item ${item.name}:`, e);
        }
      }
    }

    // Call Nano Banana (Gemini 2.5 Flash Image) API for outfit generation
    const requestBody = {
      contents: [
        {
          parts: contentParts,
        },
      ],
      generationConfig: {
        responseModalities: ["TEXT", "IMAGE"],
      },
    };

    console.log("Nano Banana request - items:", validItems.length, "parts:", contentParts.length);

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(requestBody),
      }
    );

    if (!response.ok) {
      const errorText = await response.text();
      console.error("Gemini API error response:", errorText);
      let errorMessage = `Gemini API error: ${response.status}`;
      try {
        const errorJson = JSON.parse(errorText);
        if (errorJson.error?.message) {
          errorMessage = `Gemini: ${errorJson.error.message}`;
        }
      } catch {
        // Keep the original error message
      }
      throw new Error(errorMessage);
    }

    const result = await response.json();
    console.log("Gemini response candidates:", result.candidates?.length);

    // Extract the image data from the response
    const imageData = result.candidates?.[0]?.content?.parts?.find(
      (part: { inlineData?: { mimeType: string; data: string } }) =>
        part.inlineData?.mimeType?.startsWith("image/")
    );

    if (!imageData?.inlineData?.data) {
      // Log what we got back for debugging
      const partTypes = result.candidates?.[0]?.content?.parts?.map(
        (p: { text?: string; inlineData?: unknown }) => p.text ? "text" : p.inlineData ? "inlineData" : "unknown"
      );
      console.error("No image in response. Part types:", partTypes);
      throw new Error("No image generated by Gemini. The model may not support image generation for this request.");
    }

    // Upload to storage
    const imageBytes = Uint8Array.from(atob(imageData.inlineData.data), (c) =>
      c.charCodeAt(0)
    );
    const blob = new Blob([imageBytes], {
      type: imageData.inlineData.mimeType,
    });
    const storageId = await ctx.storage.store(blob);

    // Save outfit image record
    const userPhotoIdResult = args.userPhotoStorageId
      ? await ctx.runQuery(internal.gemini.getUserPhotoIdByStorageId, {
          clerkId: args.clerkId,
          storageId: args.userPhotoStorageId,
        })
      : undefined;
    const userPhotoId: Id<"user_photos"> | undefined = userPhotoIdResult ?? undefined;

    const outfitId: Id<"outfit_images"> = await ctx.runMutation(internal.gemini.saveOutfitRecord, {
      clerkId: args.clerkId,
      storageId,
      closetItemIds: [], // No longer tracking closet item IDs since we use productIds now
      userPhotoId,
      prompt: textPrompt,
    });

    const imageUrl = await ctx.storage.getUrl(storageId);

    return {
      outfitId,
      storageId,
      imageUrl,
    };
  },
});

// Internal query to get closet item with image info
import { internalQuery } from "./_generated/server";

export const getClosetItemWithImage = internalQuery({
  args: { itemId: v.id("closet_items") },
  handler: async (ctx, args) => {
    const item = await ctx.db.get(args.itemId);
    if (!item) return null;

    // For generated items, use the generated image storage ID
    if (item.source === "generated" && item.generatedImageStorageId) {
      return {
        ...item,
        imageStorageId: item.generatedImageStorageId,
        imageUrl: await ctx.storage.getUrl(item.generatedImageStorageId),
      };
    }

    // For URL-sourced or product-linked items, use the imageUrl
    if (item.imageUrl) {
      return {
        ...item,
        imageStorageId: null,
        imageUrl: item.imageUrl,
      };
    }

    // For product-linked items, get image from the product
    if (item.productId) {
      const product = await ctx.db.get(item.productId);
      if (product) {
        return {
          ...item,
          name: item.name ?? product.name,
          brand: item.brand ?? product.brand,
          category: item.category ?? item.customCategory ?? product.category,
          imageStorageId: null,
          imageUrl: product.imageUrl,
        };
      }
    }

    return item;
  },
});

// Internal query to get product details by productId (for wishlist items)
export const getProductWithImage = internalQuery({
  args: { productId: v.id("products") },
  handler: async (ctx, args) => {
    const product = await ctx.db.get(args.productId);
    if (!product) return null;

    return {
      name: product.name,
      brand: product.brand,
      category: product.category,
      color: product.colorName,
      material: product.material,
      imageStorageId: undefined as Id<"_storage"> | undefined,
      imageUrl: product.imageUrl,
    };
  },
});

// Internal query to get user photo ID by storage ID
export const getUserPhotoIdByStorageId = internalQuery({
  args: {
    clerkId: v.string(),
    storageId: v.id("_storage"),
  },
  handler: async (ctx, args) => {
    const photo = await ctx.db
      .query("user_photos")
      .withIndex("by_clerkId", (q) => q.eq("clerkId", args.clerkId))
      .filter((q) => q.eq(q.field("storageId"), args.storageId))
      .first();

    return photo?._id;
  },
});

// Internal mutation to save outfit record
